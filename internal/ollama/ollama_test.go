// testServer spins up a fake Ollama and returns a client pointed at it.
func testServer(t *testing.T, h http.Handler) (*Client, *httptest.Server) {
	t.Helper()
	srv := httptest.NewServer(h)
	t.Cleanup(srv.Close)
	return New(srv.URL, ""), srv
}

const tagsBody = `{
  "models": [
    {
      "name": "qwen3:8b",
      "model": "qwen3:8b",
      "modified_at": "2026-09-03T08:00:00.123456789Z",
      "size": 5150000000,
      "digest": "sha256:abc",
      "details": {
        "parent_model": "",
        "format": "gguf",
        "family": "qwen3",
        "families": ["qwen3"],
        "parameter_size": "8.2B",
        "quantization_level": "Q4_K_M"
      }
    },
    {
      "name": "gemma3:12b",
      "model": "gemma3:12b",
      "modified_at": "2026-08-01T01:02:03Z",
      "size": 8123456789,
      "digest": "sha256:def",
      "details": {
        "parent_model": "gemma3:4b",
        "format": "gguf",
        "family": "gemma3",
        "families": ["gemma3"],
        "parameter_size": "12B",
        "quantization_level": "Q4_K_M"
      }
    }
  ]
}`

func TestListParsesModels(t *testing.T) {
	c, _ := testServer(t, http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.Method != http.MethodGet || r.URL.Path != "/api/tags" {
			t.Errorf("got %s %s, want GET /api/tags", r.Method, r.URL.Path)
		}
		w.Header().Set("Content-Type", "application/json")
		w.Write([]byte(tagsBody))
	}))

	models, err := c.List(context.Background())
	if err != nil {
		t.Fatalf("List: %v", err)
	}
	if len(models) != 2 {
		t.Fatalf("len = %d, want 2", len(models))
	}

	q := models[0]
	if q.Name != "qwen3:8b" || q.Family != "qwen3" ||
		q.ParameterSize != "8.2B" || q.Quantization != "Q4_K_M" ||
		q.SizeBytes != 5150000000 {
		t.Errorf("unexpected first model: %+v", q)
	}
	wantMod := time.Date(2026, 9, 3, 8, 0, 0, 123456789, time.UTC)
	if !q.ModifiedAt.Equal(wantMod) {
		t.Errorf("ModifiedAt = %v, want %v", q.ModifiedAt, wantMod)
	}

	g := models[1]
	if g.Family != "gemma3" || g.ParameterSize != "12B" {
		t.Errorf("unexpected second model: %+v", g)
	}
}

func TestListSendsBearerToken(t *testing.T) {
	var gotAuth string
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		gotAuth = r.Header.Get("Authorization")
		w.Write([]byte(`{"models":[]}`))
	}))
	t.Cleanup(srv.Close)

	c := New(srv.URL, "sekrit")
	if _, err := c.List(context.Background()); err != nil {
		t.Fatalf("List: %v", err)
	}
	if gotAuth != "Bearer sekrit" {
		t.Errorf("Authorization = %q, want %q", gotAuth, "Bearer sekrit")
	}
}

