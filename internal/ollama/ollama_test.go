func TestAPIErrorBodySurfaced(t *testing.T) {
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		w.WriteHeader(http.StatusInternalServerError)
		w.Write([]byte(`{"error":"model 'nothere' not found"}`))
	}))
	t.Cleanup(srv.Close)

	c := New(srv.URL, "")
	_, err := c.Show(context.Background(), "nothere")
	if err == nil {
		t.Fatal("want error, got nil")
	}
	if !strings.Contains(err.Error(), "model 'nothere' not found") {
		t.Errorf("error = %v, want surfaced API message", err)
	}
}

