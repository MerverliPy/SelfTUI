const showBody = `{
  "license": "Apache-2.0",
  "modelfile": "# Modelfile generated by ollama show\nFROM qwen3:8b",
  "parameters": "stop \"<|im_end|>\"\ntemperature 0.7",
  "template": "{{ .Prompt }}",
  "details": {
    "parent_model": "",
    "format": "gguf",
    "family": "qwen3",
    "families": ["qwen3"],
    "parameter_size": "8.2B",
    "quantization_level": "Q4_K_M"
  },
  "model_info": {
    "general.architecture": "qwen3",
    "general.parameter_count": 8240000000,
    "general.file_type": 15
  },
  "projector_info": {},
  "capabilities": ["completion", "tools"]
}`

func TestShowPostsNameAndParses(t *testing.T) {
	var gotBody string
	c, _ := testServer(t, http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.Method != http.MethodPost || r.URL.Path != "/api/show" {
			t.Errorf("got %s %s, want POST /api/show", r.Method, r.URL.Path)
		}
		var req map[string]string
		if err := json.NewDecoder(r.Body).Decode(&req); err != nil {
			t.Errorf("decode request: %v", err)
		}
		gotBody = req["name"]
		w.Header().Set("Content-Type", "application/json")
		w.Write([]byte(showBody))
	}))

	d, err := c.Show(context.Background(), "qwen3:8b")
	if err != nil {
		t.Fatalf("Show: %v", err)
	}
	if gotBody != "qwen3:8b" {
		t.Errorf("request name = %q, want qwen3:8b", gotBody)
	}
	if d.License != "Apache-2.0" || d.Details.ParameterSize != "8.2B" {
		t.Errorf("unexpected details: %+v", d)
	}
	if len(d.Capabilities) != 2 || d.Capabilities[0] != "completion" {
		t.Errorf("capabilities = %v", d.Capabilities)
	}
	count, ok := d.ModelInfo["general.parameter_count"].(float64)
	if !ok || count != 8240000000 {
		t.Errorf("model_info.parameter_count = %v, want 8240000000", d.ModelInfo["general.parameter_count"])
	}
	if !strings.Contains(d.Modelfile, "FROM qwen3:8b") {
		t.Errorf("modelfile = %q", d.Modelfile)
	}
}

